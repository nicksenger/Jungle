use std::{
    env, fs,
    path::{Path, PathBuf},
};

const DEFAULT_BPM: f64 = 123.0;
const ABSOLUTE_TIME_BPM: f64 = 123.0;
const DEFAULT_BEATS_PER_BAR: u32 = 4;
const DEFAULT_BEAT_UNIT: u32 = 4;

#[derive(Debug, Clone)]
struct ScoreEvent {
    start_tick: u32,
    duration_tick: u32,
    n_midi: u8,
}

#[derive(Debug, Clone)]
struct ScoreFile {
    name: String,
    ticks_per_quarter_note: u32,
    tempo_micros_per_quarter_note: u64,
    events: Vec<ScoreEvent>,
}

#[derive(Debug, Clone)]
struct Config {
    bpm: f64,
    beats_per_bar: u32,
    beat_unit: u32,
    event_limit: Option<usize>,
    score_filter: Option<String>,
    score_dir: PathBuf,
}

#[derive(Debug, Clone, Copy)]
enum Kind {
    Whole,
    DottedHalf,
    Half,
    DottedQuarter,
    Quarter,
    DottedEighth,
    Eighth,
    DottedSixteenth,
    Sixteenth,
    ThirtySecond,
    Fractional { numerator: u32, denominator: u32 },
}

#[derive(Debug, Clone, Copy)]
struct Position {
    bar: u32,
    beat: u32,
    beat_offset_num: u32,
    beat_offset_den: u32,
}

#[derive(Debug, Clone, Copy)]
struct GridNote {
    midi: u8,
    kind: Kind,
    beats: f64,
    d_sec: f64,
    t_sec: f64,
    position: Position,
}

#[derive(Debug, Clone, Copy)]
struct SectionRange {
    name: &'static str,
    start_sec: f64,
    end_sec: Option<f64>,
}

